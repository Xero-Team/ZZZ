//! Public API snapshot gate for the `gpui` crate.
//!
//! `window.rs` and the rest of `crates/gpui/src` are a widely imported public
//! façade. Moving impl blocks between files must not silently change which
//! items downstream crates can name. A full rustdoc JSON snapshot needs a
//! nightly compiler, and the pinned toolchain is stable, so this gate parses
//! the crate's source with `syn` and records every public item path and
//! signature as a stable, sorted text manifest.
//!
//! The manifest records item paths and signatures, not attribute lists or
//! source file paths. Adding `#[non_exhaustive]` or a doc comment is an
//! intentional API change that this gate deliberately leaves to review and
//! `cargo check --workspace`; moving an item between files is deliberately
//! invisible, so the gate can protect a mechanical module split.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context as _, Result, bail};
use clap::Args;

const CRATE_SRC: &str = "crates/gpui/src";
const SNAPSHOT: &str = "crates/gpui/api-snapshot.txt";

#[derive(Args)]
pub struct GpuiApiArgs {
    /// Rewrite the snapshot with the current public API instead of comparing.
    #[arg(long)]
    bless: bool,
}

/// Run the compare-only form, suitable for the `check all` gate list.
pub fn check_snapshot() -> Result<()> {
    check(GpuiApiArgs { bless: false })
}

pub fn check(args: GpuiApiArgs) -> Result<()> {
    let current = collect().context("failed to read the gpui public API")?;
    let snapshot_path = Path::new(SNAPSHOT);

    if args.bless {
        fs::write(snapshot_path, &current)
            .with_context(|| format!("failed to write {}", snapshot_path.display()))?;
        println!(
            "wrote {} public API entries to {}",
            current.lines().count(),
            snapshot_path.display()
        );
        return Ok(());
    }

    let expected = fs::read_to_string(snapshot_path).with_context(|| {
        format!(
            "{} is missing; run `cargo xtask check gpui-api --bless` once to create it",
            snapshot_path.display()
        )
    })?;

    if current == expected {
        println!("gpui public API matches {}", snapshot_path.display());
        return Ok(());
    }

    let current_lines: Vec<&str> = current.lines().collect();
    let expected_lines: Vec<&str> = expected.lines().collect();
    let mut diff = Vec::new();
    for line in &current_lines {
        if !expected_lines.contains(line) {
            diff.push(format!("+ {line}"));
        }
    }
    for line in &expected_lines {
        if !current_lines.contains(line) {
            diff.push(format!("- {line}"));
        }
    }
    bail!(
        "gpui public API changed ({} difference(s)); review the change and \
         run `cargo xtask check gpui-api --bless` to accept:\n{}",
        diff.len(),
        diff.join("\n")
    );
}

/// Collect every public item from the crate's source files into one sorted
/// manifest. Attributes, comments, bodies, `cfg` placement, and source file
/// paths are ignored so that reorganizing a file does not look like an API
/// change.
fn collect() -> Result<String> {
    let root = Path::new(CRATE_SRC);
    let files = rust_files(root)?;
    let mut entries = BTreeSet::new();

    for file in files {
        let source = fs::read_to_string(&file)
            .with_context(|| format!("failed to read {}", file.display()))?;
        let syntax = syn::parse_file(&source)
            .with_context(|| format!("failed to parse {}", file.display()))?;
        collect_items(&syntax.items, "", &mut entries);
    }

    let mut output = String::from(
        "# gpui public API snapshot\n\
         # Generated by `cargo xtask check gpui-api --bless`. Do not edit by hand.\n\
         # Format: <item path> <kind> <signature>\n",
    );
    for entry in entries {
        output.push_str(&entry);
        output.push('\n');
    }
    Ok(output)
}

fn rust_files(root: &Path) -> Result<Vec<PathBuf>> {
    let mut files = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(directory) = pending.pop() {
        for entry in fs::read_dir(&directory)
            .with_context(|| format!("failed to read {}", directory.display()))?
        {
            let entry = entry?;
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
            } else if path.extension().is_some_and(|extension| extension == "rs") {
                files.push(path);
            }
        }
    }
    files.sort();
    Ok(files)
}

fn collect_items(items: &[syn::Item], prefix: &str, entries: &mut BTreeSet<String>) {
    for item in items {
        match item {
            syn::Item::Struct(item_struct) => {
                if is_public(&item_struct.vis) {
                    push(
                        entries,
                        prefix,
                        &item_struct.ident.to_string(),
                        "struct",
                        &struct_fields(&item_struct.fields),
                    );
                }
            }
            syn::Item::Enum(item_enum) => {
                if is_public(&item_enum.vis) {
                    push(
                        entries,
                        prefix,
                        &item_enum.ident.to_string(),
                        "enum",
                        &enum_variants(&item_enum.variants),
                    );
                }
            }
            syn::Item::Union(item_union) => {
                if is_public(&item_union.vis) {
                    push(entries, prefix, &item_union.ident.to_string(), "union", "");
                }
            }
            syn::Item::Trait(item_trait) => {
                if is_public(&item_trait.vis) {
                    push(entries, prefix, &item_trait.ident.to_string(), "trait", "");
                    collect_trait_items(&item_trait.items, &item_trait.ident.to_string(), entries);
                }
            }
            syn::Item::Fn(item_fn) => {
                if is_public(&item_fn.vis) {
                    push(
                        entries,
                        prefix,
                        &item_fn.sig.ident.to_string(),
                        "fn",
                        &signature(&item_fn.sig),
                    );
                }
            }
            syn::Item::Type(item_type) => {
                if is_public(&item_type.vis) {
                    push(entries, prefix, &item_type.ident.to_string(), "type", "");
                }
            }
            syn::Item::Const(item_const) => {
                if is_public(&item_const.vis) {
                    push(entries, prefix, &item_const.ident.to_string(), "const", "");
                }
            }
            syn::Item::Static(item_static) => {
                if is_public(&item_static.vis) {
                    push(
                        entries,
                        prefix,
                        &item_static.ident.to_string(),
                        "static",
                        "",
                    );
                }
            }
            syn::Item::Macro(item_macro) => {
                if let Some(ident) = &item_macro.ident {
                    push(entries, prefix, &ident.to_string(), "macro", "");
                }
            }
            syn::Item::Mod(item_mod) => {
                if is_public(&item_mod.vis) {
                    let name = item_mod.ident.to_string();
                    push(entries, prefix, &name, "mod", "");
                    if let Some((_, inner)) = &item_mod.content {
                        let child_prefix = join(prefix, &name);
                        collect_items(inner, &child_prefix, entries);
                    }
                }
            }
            syn::Item::Impl(item_impl) => {
                collect_impl_items(item_impl, prefix, entries);
            }
            _ => {}
        }
    }
}

fn collect_impl_items(item_impl: &syn::ItemImpl, prefix: &str, entries: &mut BTreeSet<String>) {
    let self_ty = type_name(&item_impl.self_ty);
    let trait_prefix = match &item_impl.trait_ {
        Some((path, _)) => format!("<{} as {}>", self_ty, path_name(path)),
        None => self_ty,
    };
    let base = join(prefix, &trait_prefix);

    for member in &item_impl.items {
        match member {
            syn::ImplItem::Fn(method) => {
                if is_public(&method.vis) {
                    push(
                        entries,
                        &base,
                        &method.sig.ident.to_string(),
                        "method",
                        &signature(&method.sig),
                    );
                }
            }
            syn::ImplItem::Const(constant) => {
                if is_public(&constant.vis) {
                    push(
                        entries,
                        &base,
                        &constant.ident.to_string(),
                        "assoc-const",
                        "",
                    );
                }
            }
            syn::ImplItem::Type(alias) => {
                if is_public(&alias.vis) {
                    push(entries, &base, &alias.ident.to_string(), "assoc-type", "");
                }
            }
            _ => {}
        }
    }
}

fn collect_trait_items(items: &[syn::TraitItem], trait_name: &str, entries: &mut BTreeSet<String>) {
    for item in items {
        match item {
            syn::TraitItem::Fn(method) => {
                push(
                    entries,
                    trait_name,
                    &method.sig.ident.to_string(),
                    "trait-method",
                    &signature(&method.sig),
                );
            }
            syn::TraitItem::Const(constant) => {
                push(
                    entries,
                    trait_name,
                    &constant.ident.to_string(),
                    "trait-const",
                    "",
                );
            }
            syn::TraitItem::Type(alias) => {
                push(
                    entries,
                    trait_name,
                    &alias.ident.to_string(),
                    "trait-type",
                    "",
                );
            }
            _ => {}
        }
    }
}

fn push(entries: &mut BTreeSet<String>, prefix: &str, name: &str, kind: &str, detail: &str) {
    let path = if prefix.is_empty() {
        name.to_string()
    } else {
        format!("{prefix}::{name}")
    };
    let detail = detail.replace('\n', " ");
    entries.insert(format!("{path} {kind} {detail}"));
}

fn join(prefix: &str, name: &str) -> String {
    if prefix.is_empty() {
        name.to_string()
    } else {
        format!("{prefix}::{name}")
    }
}

/// Only unrestricted `pub` is visible to downstream crates. `pub(crate)`,
/// `pub(super)`, and private items are internal implementation details; a
/// mechanical module split may need to widen one to `pub(super)` without
/// changing the public API.
fn is_public(vis: &syn::Visibility) -> bool {
    matches!(vis, syn::Visibility::Public(_))
}

fn signature(sig: &syn::Signature) -> String {
    use quote::ToTokens;
    let mut tokens = sig.inputs.to_token_stream().to_string();
    if let syn::ReturnType::Type(_, ty) = &sig.output {
        tokens.push_str(" -> ");
        tokens.push_str(&ty.to_token_stream().to_string());
    }
    if let Some(generics) = split_generics(sig) {
        tokens = format!("{generics} {tokens}");
    }
    tokens
}

fn split_generics(sig: &syn::Signature) -> Option<String> {
    use quote::ToTokens;
    if sig.generics.params.is_empty() {
        return None;
    }
    let params = sig.generics.params.to_token_stream().to_string();
    let where_clause = sig
        .generics
        .where_clause
        .as_ref()
        .map(|clause| clause.to_token_stream().to_string())
        .unwrap_or_default();
    Some(format!("<{params}> {where_clause}"))
}

fn struct_fields(fields: &syn::Fields) -> String {
    let mut names = Vec::new();
    match fields {
        syn::Fields::Named(named) => {
            for field in &named.named {
                if is_public(&field.vis)
                    && let Some(ident) = &field.ident
                {
                    names.push(ident.to_string());
                }
            }
        }
        syn::Fields::Unnamed(unnamed) => {
            for (index, field) in unnamed.unnamed.iter().enumerate() {
                if is_public(&field.vis) {
                    names.push(index.to_string());
                }
            }
        }
        syn::Fields::Unit => {}
    }
    names.join(",")
}

fn enum_variants(
    variants: &syn::punctuated::Punctuated<syn::Variant, syn::token::Comma>,
) -> String {
    variants
        .iter()
        .map(|variant| variant.ident.to_string())
        .collect::<Vec<_>>()
        .join(",")
}

fn type_name(ty: &syn::Type) -> String {
    use quote::ToTokens;
    ty.to_token_stream().to_string().replace(' ', "")
}

fn path_name(path: &syn::Path) -> String {
    use quote::ToTokens;
    path.to_token_stream().to_string().replace(' ', "")
}

#[cfg(test)]
mod tests {
    use super::collect_items;

    fn entries(source: &str) -> Vec<String> {
        let syntax = syn::parse_file(source).expect("test source should parse");
        let mut entries = std::collections::BTreeSet::new();
        collect_items(&syntax.items, "", &mut entries);
        entries.into_iter().collect()
    }

    #[test]
    fn records_a_public_struct_with_its_public_fields() {
        let collected = entries(
            r#"
            pub struct Style {
                pub size: f32,
                hidden: bool,
            }
            "#,
        );
        assert_eq!(collected, vec!["Style struct size"]);
    }

    #[test]
    fn detects_a_changed_method_signature() {
        let before = entries("impl Foo { pub fn render(&self, cx: &App) {} }");
        let after = entries("impl Foo { pub fn render(&self, cx: &App, scale: f32) {} }");
        assert_ne!(
            before, after,
            "a changed public method signature must change the snapshot"
        );
    }

    #[test]
    fn ignores_crate_private_items() {
        let collected = entries(
            r#"
            pub(crate) fn internal() {}
            pub fn external() {}
            "#,
        );
        assert_eq!(collected, vec!["external fn "]);
    }

    #[test]
    fn ignores_attributes_comments_and_file_paths() {
        let plain = entries("pub struct Specs { pub name: String }");
        let annotated = entries(
            r#"
            /// Docs are not part of the signature.
            #[non_exhaustive]
            pub struct Specs {
                pub name: String,
            }
            "#,
        );
        assert_eq!(
            plain, annotated,
            "adding an attribute or a doc comment must not look like an API change"
        );
    }
}
